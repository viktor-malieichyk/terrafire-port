def read_table(img, addr):
    out = []
    while True:
        (v,) = struct.unpack_from('<I', img, addr - IMAGE_BASE)
        if v == 0:
            return out
        out.append(v)
        addr += 4


def main(image_path, out_dir):
    img = open(image_path, 'rb').read()
    anims = read_table(img, ANIM_TABLE)
    table_count = len(anims)
    anims += [a for a in EXTRA_ANIMS if a not in anims]
    callbacks = read_table(img, CALLBACK_TABLE)
    hdr = '/* Generated by re/tools/gen_objects.py from PART2.EXE - do not edit. */\n'

    with open(os.path.join(out_dir, 'anims.h'), 'w') as w:
        w.write(hdr + '#ifndef TF_ANIMS_H\n#define TF_ANIMS_H\n\n#include <stdint.h>\n\n')
        w.write('typedef struct {\n    int16_t image;   /* bank or frame slot, -1 = keep */\n'
                '    uint16_t op;     /* 1 mirror, 2/3 rotate; others none */\n'
                '    int16_t dx, dy;  /* applied through the object orientation */\n} AnimFrame;\n\n')
        w.write('typedef struct {\n    uint8_t loop;\n    int16_t count;\n    const AnimFrame *frames;\n'
                '    uint32_t orig_addr;\n} AnimDef;\n\n')
        w.write(f'#define ANIM_COUNT {len(anims)}\n'
                f'#define ANIM_TABLE_COUNT {table_count}   /* listed in 0x56f54 (save indices) */\n\nenum {{\n')
        for i, a in enumerate(anims):
            w.write(f'    ANIM_{a:05x} = {i},\n')
        w.write('};\n\nextern const AnimDef g_anims[ANIM_COUNT];\n\n#endif\n')

    with open(os.path.join(out_dir, 'anims_data.c'), 'w') as w:
        w.write(hdr + '#include "anims.h"\n\n')
        for i, a in enumerate(anims):
            count = struct.unpack_from('<h', img, a - IMAGE_BASE + 1)[0]
            (frames,) = struct.unpack_from('<I', img, a - IMAGE_BASE + 3)
            w.write(f'static const AnimFrame s_frames_{i}[{count}] = {{\n')
            for k in range(count):
                image, op, dx, dy = struct.unpack_from('<hHhh', img, frames - IMAGE_BASE + k * 8)
                w.write(f'    {{ {image}, {op}, {dx}, {dy} }},\n')
            w.write('};\n')
        w.write('\nconst AnimDef g_anims[ANIM_COUNT] = {\n')
        for i, a in enumerate(anims):
            loop = img[a - IMAGE_BASE]
            count = struct.unpack_from('<h', img, a - IMAGE_BASE + 1)[0]
            w.write(f'    {{ {loop}, {count}, s_frames_{i}, 0x{a:05x} }},\n')
        w.write('};\n')

    with open(os.path.join(out_dir, 'callbacks.h'), 'w') as w:
        w.write(hdr + '#ifndef TF_CALLBACKS_H\n#define TF_CALLBACKS_H\n\n#include <stdint.h>\n\n')
        w.write('typedef void (*ObjCallback)(int slot);\n\n')
        w.write(f'#define CALLBACK_COUNT {len(callbacks)}\n\nenum {{\n')
        for i, c in enumerate(callbacks):
            w.write(f'    CB_{c:05x} = {i},\n')
        w.write('};\n\nextern const ObjCallback g_callbacks[CALLBACK_COUNT];\n'
                'extern const uint32_t g_callback_addr[CALLBACK_COUNT];\n\n')
        for name in sorted(set(PORTED.values())):
            w.write(f'void {name}(int slot);\n')
        w.write('\n#endif\n')

    with open(os.path.join(out_dir, 'callbacks_data.c'), 'w') as w:
        w.write(hdr + '#include "callbacks.h"\n\n#include "objects.h"\n#include "unported.h"\n\n')
        for c in callbacks:
            if c not in PORTED:
                w.write(f'static void cb_{c:05x}(int slot) {{ (void)slot; UNPORTED("0x{c:05x}", "object callback"); }}\n')
        w.write('\nconst ObjCallback g_callbacks[CALLBACK_COUNT] = {\n')
        for c in callbacks:
            w.write(f'    {PORTED.get(c, f"cb_{c:05x}")},\n')
        w.write('};\n\nconst uint32_t g_callback_addr[CALLBACK_COUNT] = {\n')
        for c in callbacks:
            w.write(f'    0x{c:05x},\n')
        w.write('};\n')
    print(f'{len(anims)} animations, {len(callbacks)} callbacks ({len(PORTED)} ported)')


if __name__ == '__main__':
    main(*sys.argv[1:3])
