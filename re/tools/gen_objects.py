#!/usr/bin/env python3
"""Generate the port's animation and object-callback tables from PART2.EXE.

Both tables are NULL-terminated pointer lists the original's save code uses
to turn pointers into indices (0x277c4 / 0x2756c), so keeping their order
keeps the legacy save format readable:

    0x56f54  animation definitions:  u8 loop; s16 count; u32 frames ->
             count x { s16 image; u16 op; s16 dx; s16 dy }
    0x56e04  object callbacks (code addresses)

Usage: gen_objects.py build/part2.bin ../port/src
Writes anims.h, anims_data.c, callbacks.h, callbacks_data.c.
Callbacks listed in PORTED are expected to be implemented by hand in the
port; every other one gets a generated logging stub.
"""
import os
import struct
import sys

IMAGE_BASE = 0x10000
ANIM_TABLE = 0x56f54
CALLBACK_TABLE = 0x56e04

# Animations the code uses that the table does not list (so saves cannot
# reference them): appended after the table entries.
EXTRA_ANIMS = [0x44510, 0x56088, 0x5608f, 0x56096, 0x5609d, 0x560a4, 0x560ab, 0x560b2, 0x560b9]

