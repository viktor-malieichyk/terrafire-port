#!/usr/bin/env python3
"""Generate small constant tables from PART2.EXE into port/src/tables_data.c.

  0x42b18  361 x s32  trig table A, indexed by angle in degrees (used for x)
  0x430bc  361 x s32  trig table B, indexed by angle in degrees (used for y)
  0x43660  256 x s32  pseudo-random values (used e.g. for pod start frames)
  0x56494  18 x 3 s32 bullet banks per weapon level (two alternating barrels, extra)
  0x43c10  34 x 0x38 sound table (loaded by 0x23300, played by 0x2e4a8)

Usage: gen_tables.py build/part2.bin ../port/src/tables_data.c
"""
import struct
import sys

IMAGE_BASE = 0x10000
RANDOM_TABLE = 0x43660
TRIG_A, TRIG_B = 0x42b18, 0x430bc
WEAPON_TABLE, WEAPON_LEVELS = 0x56494, 18

img = open(sys.argv[1], 'rb').read()


def table(name, addr, count):
    vals = struct.unpack_from(f'<{count}i', img, addr - IMAGE_BASE)
    rows = [', '.join(str(v) for v in vals[i:i + 8]) for i in range(0, count, 8)]
    return f'const int32_t {name}[{count}] = {{   /* 0x{addr:05x} */\n    ' + ',\n    '.join(rows) + ',\n};\n'


TEXT_TABLE, TEXT_END = 0x4276c, 0x4276c + 235 * 4   # message pointers (English column)
KEY_NAMES = 0x59620                        # 128 x 16-byte key names by scancode


def c_string(b):
    out = ''
    for ch in b:
        if ch == 0x22 or ch == 0x5c: out += '\\' + chr(ch)
        elif 32 <= ch < 127: out += chr(ch)
        else: out += '\\%03o' % ch
    return '"' + out + '"'


def text_table():
    rows = []
    for a in range(TEXT_TABLE, TEXT_END, 4):
        (p,) = struct.unpack_from('<I', img, a - IMAGE_BASE)
        if 0x40000 <= p < 0x60000:
            e = img.index(b'\0', p - IMAGE_BASE)
            rows.append('    ' + c_string(img[p - IMAGE_BASE:e]) + ',')
        else:
            rows.append('    "",')
    n = (TEXT_END - TEXT_TABLE) // 4
    return f'const char *const g_text[{n}] = {{   /* 0x{TEXT_TABLE:05x} */\n' + '\n'.join(rows) + '\n};\n'


def key_names():
    rows = []
    for k in range(128):
        a = KEY_NAMES + k * 16 - IMAGE_BASE
        rows.append('    ' + c_string(img[a:a + 16].split(b'\0')[0]) + ',')
    return f'const char *const g_key_names[128] = {{   /* 0x{KEY_NAMES:05x} */\n' + '\n'.join(rows) + '\n};\n'


# The original indexes the trig tables with unchecked angles down to -19
# (e.g. 0x23f58), reading the static data before them; keep it.
TRIG_BEFORE = 19
SOUND_TABLE, SOUNDS = 0x43c10, 34


def sound_table():
    rows = []
    for i in range(SOUNDS):
        (entry, volume, _last, retrigger, stop_next, skip_next, _data,
         flags) = struct.unpack_from('<iiiiiiiI', img, SOUND_TABLE - IMAGE_BASE + i * 0x38)
        rows.append(f'    {{ {entry}, {volume}, {retrigger}, {stop_next}, {skip_next}, '
                    f'{flags >> 16}, {"false" if flags & 0xffff else "true"} }},   /* {i} */')
    return (f'const SoundDef g_sound_table[{SOUNDS}] = {{   /* 0x{SOUND_TABLE:05x} */\n'
            + '\n'.join(rows) + '\n};\n')


assert TRIG_A + 361 * 4 == TRIG_B and TRIG_B + 361 * 4 == RANDOM_TABLE
open(sys.argv[2], 'w').write(
    '/* Generated by re/tools/gen_tables.py from PART2.EXE - do not edit. */\n'
    '#include "tables.h"\n\n' +
    table('g_trig_mem', TRIG_A - TRIG_BEFORE * 4, TRIG_BEFORE + 722) + '\n' +
    table('g_random_table', RANDOM_TABLE, 256) + '\n' +
    table('g_weapon_banks', WEAPON_TABLE, WEAPON_LEVELS * 3) + '\n' + sound_table() + '\n' + text_table() + '\n' + key_names())
